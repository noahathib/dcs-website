// Regenerates src/data/imageSizes.ts from the WebP files in public/img.
// Run after adding or replacing images: npm run images
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

function webpSize(buf) {
  const chunk = buf.toString("ascii", 12, 16);
  if (chunk === "VP8X") return [1 + buf.readUIntLE(24, 3), 1 + buf.readUIntLE(27, 3)];
  if (chunk === "VP8 ") return [buf.readUInt16LE(26) & 0x3fff, buf.readUInt16LE(28) & 0x3fff];
  if (chunk === "VP8L") {
    const b = buf.readUInt32LE(21);
    return [(b & 0x3fff) + 1, ((b >> 14) & 0x3fff) + 1];
  }
  throw new Error(`Unrecognized WebP chunk ${chunk}`);
}

const rows = readdirSync("public/img")
  .filter((f) => f.endsWith(".webp"))
  .sort()
  .map((f) => {
    const [w, h] = webpSize(readFileSync(`public/img/${f}`));
    return `  "${f.replace(/\.webp$/, "")}": [${w}, ${h}],`;
  });

writeFileSync(
  "src/data/imageSizes.ts",
  `// Generated by scripts/image-sizes.mjs (npm run images). Intrinsic WebP sizes for width/height attributes.\nexport const IMAGE_SIZES: Record<string, [number, number]> = {\n${rows.join("\n")}\n};\n`,
);
console.log(`${rows.length} images`);
